def _traduzir_sql(texto: str, parametros) -> str:
    """Ajusta o SQL do projeto para o dialeto do Postgres.

    Só duas construções precisam de tradução: `GROUP_CONCAT(x, sep)` vira
    `string_agg(x, sep)` e o marcador `?` vira `%s`. Em consultas com
    parâmetros, o sinal `%` literal do texto (por exemplo em um LIKE '%termo%')
    precisa ser duplicado para o psycopg.
    """
    texto = texto.replace("GROUP_CONCAT(", "string_agg(")
    if parametros:
        texto = texto.replace("%", "%%")
    return texto.replace("?", "%s")


class _Cursor:
    """Cursor do psycopg com os métodos usados pelo projeto."""

    def __init__(self, cursor):
        self._cursor = cursor
        self.rowcount = getattr(cursor, "rowcount", -1)

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor)


class _Conexao:
    """Conexão com execute/executemany/commit/rollback/close usados pelo projeto."""

    def __init__(self, conexao):
        self._conexao = conexao

    def execute(self, sql: str, parametros=None) -> _Cursor:
        cursor = self._conexao.cursor()
        consulta = _traduzir_sql(sql, parametros)
        if parametros is None:
            cursor.execute(consulta)
        else:
            cursor.execute(consulta, parametros)
        return _Cursor(cursor)

    def executemany(self, sql: str, sequencia) -> _Cursor:
        cursor = self._conexao.cursor()
        cursor.executemany(_traduzir_sql(sql, sequencia), sequencia)
        return _Cursor(cursor)

    def executescript(self, script: str) -> None:
        # O psycopg executa um comando por vez: o script de criação das tabelas
        # é enviado separado por ponto e vírgula.
        for comando in script.split(";"):
            if comando.strip():
                self.execute(comando)

    def commit(self) -> None:
        self._conexao.commit()

    def rollback(self) -> None:
        self._conexao.rollback()

    def close(self) -> None:
        self._conexao.close()


def conectar() -> _Conexao:
    """Abre a conexão com o Postgres, com as linhas acessíveis por nome."""
    if not URL_BANCO:
        raise RuntimeError(
            "SENTINELA_DB_URL não está definido. Copie a string de conexão do "
            "Postgres (Neon/Supabase) para as variáveis de ambiente do serviço."
        )
    return _Conexao(
        psycopg.connect(
            URL_BANCO,
            row_factory=dict_row,
            connect_timeout=15,
            # O pooler do Supabase (porta 6543) recusa prepared statements.
            prepare_threshold=None,
        )
    )


def inserir_id(conexao_aberta: _Conexao, sql: str, parametros) -> int:
    """Executa um INSERT e devolve o id criado (RETURNING id)."""
    cursor = conexao_aberta.execute(
        sql.rstrip().rstrip(";") + " RETURNING id", parametros
    )
    linha = cursor.fetchone()
    return linha["id"] if linha else None


