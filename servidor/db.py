def _aplicar_migracoes(conexao_aberta: _Conexao) -> None:
    """Aplica migrações uma única vez, registrando a versão no banco.

    O esquema base é sempre idempotente; as migrações cobrem colunas que não
    existiam em bancos antigos. A versão 001 é registrada à parte para não
    executar o esquema duas vezes.
    """
    conexao_aberta.executescript(ESQUEMA_POSTGRES)
    base = conexao_aberta.execute(
        "SELECT 1 FROM schema_migrations WHERE versao = ?", ("001_esquema_base",)
    ).fetchone()
    if base is None:
        conexao_aberta.execute(
            "INSERT INTO schema_migrations (versao, aplicada_em) VALUES (?, ?)",
            ("001_esquema_base", datetime.utcnow().isoformat(timespec="seconds")),
        )
    for versao, sql in MIGRACOES:
        existente = conexao_aberta.execute(
            "SELECT 1 FROM schema_migrations WHERE versao = ?", (versao,)
        ).fetchone()
        if existente:
            continue
        conexao_aberta.executescript(sql)
        conexao_aberta.execute(
            "INSERT INTO schema_migrations (versao, aplicada_em) VALUES (?, ?)",
            (versao, datetime.utcnow().isoformat(timespec="seconds")),
        )


def _semear_matriz(conexao_aberta: _Conexao, forcar_atualizacao: bool) -> None:
    """Copia para o banco as áreas e regras que nascem em dados/regras.json.

    A semente é descartada depois da publicação, para o processo não guardar
    uma segunda cópia da matriz: a tabela regras é a fonte única.
    """
    regras_de_seed = {}
    for regra in seed.listar():
        regras_de_seed.setdefault(regra["area"], []).append(regra)

    for area in AREAS:
        linha = conexao_aberta.execute(
            "SELECT id FROM areas WHERE nome = ?", (area["nome"],)
        ).fetchone()
        if linha is None:
            area_id = inserir_id(
                conexao_aberta,
                "INSERT INTO areas (nome, descricao) VALUES (?, ?)",
                (area["nome"], area["descricao"]),
            )
        else:
            area_id = linha["id"]
            if forcar_atualizacao:
                conexao_aberta.execute(
                    "UPDATE areas SET descricao = ? WHERE id = ?",
                    (area["descricao"], area_id),
                )

        for regra in regras_de_seed.get(area["nome"], []):
            existente = conexao_aberta.execute(
                "SELECT id FROM regras WHERE area_id = ? AND nome = ?",
                (area_id, regra["nome"]),
            ).fetchone()
            if existente is None:
                conexao_aberta.execute(
                    """
                    INSERT INTO regras (area_id, nome, tipo, padrao, risco, ativo)
                    VALUES (?, ?, ?, ?, ?, 1)
                    """,
                    (area_id, regra["nome"], regra["tipo"], regra["padrao"], regra["risco"]),
                )
            elif forcar_atualizacao:
                conexao_aberta.execute(
                    "UPDATE regras SET tipo = ?, padrao = ?, risco = ? WHERE id = ?",
                    (regra["tipo"], regra["padrao"], regra["risco"], existente["id"]),
                )


def _semear_sites(conexao_aberta: _Conexao) -> None:
    """Garante no banco os chats conhecidos do catálogo.

    Os sites padrão podem ter nome/URL editados no painel. Por isso o seed usa
    DO NOTHING: ele cria o que falta, mas não desfaz uma edição do cliente.
    """
    agora = datetime.now().isoformat(timespec="seconds")
    for site in SITES_MONITORADOS:
        conexao_aberta.execute(
            """
            INSERT INTO sites_monitorados
                (id, nome, hosts, campos, enviar, padrao, criado_em, atualizado_em)
            VALUES (?, ?, ?, ?, ?, 1, ?, ?)
            ON CONFLICT(id) DO NOTHING
            """,
            (
                site["id"],
                site["nome"],
                json.dumps(site["hosts"], ensure_ascii=False),
                json.dumps(site.get("campos", []), ensure_ascii=False),
                json.dumps(site.get("enviar", []), ensure_ascii=False),
                agora,
                agora,
            ),
        )


def _migrar_senhas_em_texto(conexao_aberta: _Conexao) -> None:
    """Converte senhas antigas gravadas sem hash para scrypt.

    O sistema sempre criou hash, mas esta migration cobre bancos importados de
    versões anteriores ou de outro sistema. Depois dela, nenhuma linha guarda
    a senha legível.
    """
    linhas = conexao_aberta.execute(
        "SELECT id, senha_hash FROM usuarios_admin"
    ).fetchall()
    for linha in linhas:
        valor = linha["senha_hash"] or ""
        if valor and not senha_ja_hasheada(valor):
            conexao_aberta.execute(
                "UPDATE usuarios_admin SET senha_hash = ? WHERE id = ?",
                (hash_senha(valor), linha["id"]),
            )


def inicializar_banco(usuario: str, senha: str) -> None:
    """Cria o esquema, sincroniza a matriz e garante o administrador inicial."""
    conexao_aberta = conectar()
    try:
        # Serializa a inicialização entre instâncias do Render/Cloud Run. Sem isso,
        # dois cold starts poderiam tentar semear o banco ao mesmo tempo.
        conexao_aberta.execute("SELECT pg_advisory_xact_lock(728028)")
        _aplicar_migracoes(conexao_aberta)
        _semear_sites(conexao_aberta)

        for nome_antigo, nome_novo in RENOMEACOES_DE_REGRAS.items():
            conexao_aberta.execute(
                "UPDATE regras SET nome = ? WHERE nome = ?", (nome_novo, nome_antigo)
            )

        versao = conexao_aberta.execute(
            "SELECT valor FROM configuracoes WHERE chave = 'matriz_versao'"
        ).fetchone()
        atualizar = versao is None or versao["valor"] != VERSAO_MATRIZ
        _semear_matriz(conexao_aberta, atualizar)
        seed.limpar()

        if atualizar:
            conexao_aberta.execute(
                """
                INSERT INTO configuracoes (chave, valor) VALUES ('matriz_versao', ?)
                ON CONFLICT(chave) DO UPDATE SET valor = excluded.valor
                """,
                (VERSAO_MATRIZ,),
            )

        # Mensagens padrão são sincronizadas em toda inicialização. A atualização
        # só atinge textos que ainda são exatamente os padrões antigos, então uma
        # mensagem personalizada no painel nunca é sobrescrita.
        for nivel, texto in MENSAGENS_PADRAO.items():
            conexao_aberta.execute(
                """
                INSERT INTO mensagens (nivel, texto) VALUES (?, ?)
                ON CONFLICT(nivel) DO NOTHING
                """,
                (nivel, texto),
            )

        conexao_aberta.execute(
            "UPDATE mensagens SET texto = ? WHERE nivel = 'baixo' AND texto = ?",
            (MENSAGENS_PADRAO["baixo"], MENSAGEM_BAIXO_ANTERIOR),
        )
        for nivel, texto_anterior in MENSAGENS_DA_VERSAO_ANTERIOR.items():
            conexao_aberta.execute(
                "UPDATE mensagens SET texto = ? WHERE nivel = ? AND texto = ?",
                (MENSAGENS_PADRAO[nivel], nivel, texto_anterior),
            )
        for nivel, texto_anterior in MENSAGENS_DA_VERSAO_2_9.items():
            conexao_aberta.execute(
                "UPDATE mensagens SET texto = ? WHERE nivel = ? AND texto = ?",
                (MENSAGENS_PADRAO[nivel], nivel, texto_anterior),
            )

        # Textos antigos que circularam em bancos de demonstração. O LIKE cobre
        # variações do mesmo aviso sem tocar em mensagens personalizadas.
        conexao_aberta.execute(
            "UPDATE mensagens SET texto = ? WHERE nivel = 'baixo' AND texto LIKE 'Nenhum dado crítico detectado%'",
            (MENSAGENS_PADRAO["baixo"],),
        )
        conexao_aberta.execute(
            "UPDATE mensagens SET texto = ? WHERE nivel = 'alto' AND texto = ?",
            (MENSAGENS_PADRAO["alto"], "Não compartilhe este conteúdo."),
        )

        conexao_aberta.execute(
            """
            INSERT INTO configuracoes (chave, valor) VALUES (?, ?)
            ON CONFLICT(chave) DO NOTHING
            """,
            ("limiar_gargalo", "30"),
        )

        # Política de monitoramento definida no painel. A extensão recebe
        # estes valores em /api/config; não há mais interruptor local.
        conexao_aberta.execute(
            """
            INSERT INTO configuracoes (chave, valor) VALUES (?, ?)
            ON CONFLICT(chave) DO NOTHING
            """,
            ("monitoramento_ativo", "1"),
        )
        conexao_aberta.execute(
            """
            INSERT INTO configuracoes (chave, valor) VALUES (?, ?)
            ON CONFLICT(chave) DO NOTHING
            """,
            ("sites_ativos", json.dumps(SITES_PADRAO)),
        )

        # 2.2: código de verificação usado pelas extensões quando o servidor está
        # publicado na internet. Gerado uma vez e guardado no banco.
        conexao_aberta.execute(
            """
            INSERT INTO configuracoes (chave, valor) VALUES (?, ?)
            ON CONFLICT(chave) DO NOTHING
            """,
            ("api_token", secrets.token_urlsafe(32)),
        )
        # Versão do código: aumenta a cada renovação para o painel identificar
        # quais dispositivos ainda usam o código anterior.
        conexao_aberta.execute(
            """
            INSERT INTO configuracoes (chave, valor) VALUES (?, ?)
            ON CONFLICT(chave) DO NOTHING
            """,
            ("api_token_versao", "1"),
        )
        # Muda sempre que regra, área, mensagem ou política é alterada. A
        # extensão compara esta versão antes de baixar a matriz inteira.
        conexao_aberta.execute(
            """
            INSERT INTO configuracoes (chave, valor) VALUES (?, ?)
            ON CONFLICT(chave) DO NOTHING
            """,
            ("config_versao", "1"),
        )

        existente = conexao_aberta.execute(
            "SELECT id, superadmin FROM usuarios_admin WHERE LOWER(usuario) = LOWER(?)",
            (usuario,),
        ).fetchone()
        if not existente:
            conexao_aberta.execute(
                """
                INSERT INTO usuarios_admin (usuario, senha_hash, criado_em, superadmin)
                VALUES (?, ?, ?, 1)
                """,
                (usuario, hash_senha(senha), datetime.now().isoformat(timespec="seconds")),
            )
        elif not existente.get("superadmin"):
            # Bancos antigos recebem a coluna pela migração; só promovemos o
            # administrador inicial se ainda não houver nenhum superadmin.
            superadmin = conexao_aberta.execute(
                "SELECT id FROM usuarios_admin WHERE superadmin = 1 LIMIT 1"
            ).fetchone()
            if not superadmin:
                conexao_aberta.execute(
                    "UPDATE usuarios_admin SET superadmin = 1 WHERE id = ?",
                    (existente["id"],),
                )

        _migrar_senhas_em_texto(conexao_aberta)
        conexao_aberta.commit()
    finally:
        conexao_aberta.close()


